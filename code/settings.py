合法频率 = ("月", "季", "半年", "年")
警告 = []


def _合并(默认, 用户):
    out = copy.deepcopy(默认)
    if not isinstance(用户, dict):
        return out
    for k, v in 用户.items():
        if k.startswith("_"):
            continue
        if k in out and isinstance(out[k], dict) and isinstance(v, dict):
            out[k] = _合并(out[k], v)
        elif k in out:
            out[k] = v
        # 配置里多出来的键直接忽略，不让打错的键悄悄生效
    return out


def _校验(cfg):
    global 警告
    警告 = []
    for 段 in cfg.values():
        if not isinstance(段, dict):
            continue
        for k, v in list(段.items()):
            if k not in 范围:
                continue
            lo, hi, 名 = 范围[k]
            try:
                x = float(v)
            except (TypeError, ValueError):
                段[k] = 默认值(k)
                警告.append(f"{名} 不是数字，已回退到默认值 {段[k]}")
                continue
            if x < lo or x > hi:
                段[k] = type(默认值(k))(min(max(x, lo), hi))
                警告.append(f"{名} 应在 {lo}~{hi} 之间，已夹到 {段[k]}")
            else:
                段[k] = type(默认值(k))(x) if isinstance(默认值(k), int) else x

    f = cfg["调仓"]["调仓频率"]
    if f not in 合法频率:
        cfg["调仓"]["调仓频率"] = "季"
        警告.append(f"调仓频率「{f}」不认识，只能是 月/季/半年/年，已用「季」")

    w = cfg["因子权重"]
    if sum(float(x) for x in w.values()) <= 0:
        cfg["因子权重"] = dict(默认配置["因子权重"])
        警告.append("四个因子权重不能全是 0，已回退到等权")

    # 单笔最小金额 与 持仓上限 冲突时，以资金为准给出提示
    资 = cfg["资金与成本"]["初始资金"]
    最小 = cfg["资金与成本"]["单笔最小金额"]
    if 最小 > 0 and 资 / 最小 < 1:
        警告.append(f"单笔最小金额 {最小:.0f} 元 > 全部资金 {资:.0f} 元，"
                    f"将只能买 1 只；建议把单笔最小金额降到 {资:.0f} 元以内")
    return cfg


def 默认值(键):
    for 段 in 默认配置.values():
        if isinstance(段, dict) and 键 in 段:
            return 段[键]
    return None


def 读配置(路径=None):
    """读 config.json。文件不存在或坏掉都不致命，回退默认并记录警告。"""
    global 警告
    p = 路径 or 配置文件
    用户 = {}
    if os.path.exists(p):
        try:
            with open(p, encoding="utf-8") as f:
                用户 = json.load(f)
        except Exception as e:
            用户 = {}
            警告.append(f"config.json 读不出来（{e}），本次全部用默认参数")
    else:
        警告.append("没找到 config.json，本次用默认参数")
    return _校验(_合并(默认配置, 用户))


def 写配置(cfg, 路径=None):
    p = 路径 or 配置文件
    out = _校验(_合并(默认配置, cfg))
    out["_说明"] = 默认配置.get("_说明", "选股工具参数。改完必须重跑回测验证。")
    with open(p, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    return out


