# 成本预估 —— 界面上实时显示，让用户在跑之前就看见代价
# ============================================================
每年调仓次数 = {"月": 12, "季": 4, "半年": 2, "年": 1}


def 成本预估(cfg, 平均换手率=0.5):
    """粗算一年的交易成本占比。

    这不是回测，是让用户在动旋钮的当下就看到量级。
    模型：每期换掉 平均换手率 × 持仓数 只，一卖一买两笔，
    每笔佣金 = max(金额×费率, 佣金最低)，再加印花税(卖)、过户费(双边)、滑点(双边)。
    本项目实测：2500 元、月调仓、持仓中位 8 只 → 年化成本 7.2%，与此模型同量级。
    """
    资 = float(cfg["资金与成本"]["初始资金"])
    费率 = float(cfg["资金与成本"]["佣金费率"])
    最低 = float(cfg["资金与成本"]["佣金最低"])
    印花 = float(cfg["资金与成本"]["印花税率"])
    过户 = float(cfg["资金与成本"]["过户费率"])
    滑点 = float(cfg["资金与成本"]["滑点率"])
    单笔最小 = float(cfg["资金与成本"]["单笔最小金额"])
    上限N = int(cfg["调仓"]["持仓上限"])
    每年 = 每年调仓次数.get(cfg["调仓"]["调仓频率"], 4)

    N = 上限N if 单笔最小 <= 0 else max(1, min(上限N, int(资 // 单笔最小)))
    仓位 = 资 / N if N else 资
    换手只数 = max(0.0, 平均换手率 * N)

    卖额 = 换手只数 * 仓位
    买额 = 换手只数 * 仓位
    佣金 = 换手只数 * (max(仓位 * 费率, 最低) * 2)      # 一卖一买
    单期 = (佣金 + 卖额 * 印花 + (买额 + 卖额) * 过户
            + (买额 + 卖额) * 滑点)
    年成本 = 单期 * 每年
    return {
        "实际持仓数": N,
        "每仓金额": round(仓位, 1),
        "单笔佣金": round(max(仓位 * 费率, 最低), 2),
        "单笔佣金占比%": round(max(仓位 * 费率, 最低) / 仓位 * 100, 3) if 仓位 else 0,
        "每年调仓次数": 每年,
        "每期成本": round(单期, 1),
        "每年成本": round(年成本, 1),
        "年成本占比%": round(年成本 / 资 * 100, 2) if 资 else 0,
    }


